test("analytics usage snapshots aggregate every active account and retain legacy rows separately", () => {
  const orchestrator = read("workers/backend-orchestrator/src/index.ts")
  const analyticsRoute = read("src/app/api/dashboard/analytics/route.ts")
  const panelSchema = read("src/lib/db.ts")

  assert.match(orchestrator, /scope text not null default 'account'/)
  assert.match(orchestrator, /partition by scope, captured_day/)
  assert.match(orchestrator, /left join drive_bucket_stats stats on stats\.account_id = a\.id[\s\S]*?where a\.status = 'active'/)
  assert.match(orchestrator, /'system', 'All active accounts'/)
  assert.match(orchestrator, /on conflict \(scope, captured_day\) do update set/)
  assert.match(analyticsRoute, /where scope='system'/)
  assert.match(analyticsRoute, /join public\.drive_accounts a on a\.id=s\.account_id and a\.status='active'/)
  assert.match(analyticsRoute, /activeAccounts\.reduce\(\(sum, account\) => sum \+ toNumber\(account\.totalBytes\)/)
  assert.match(analyticsRoute, /accountLabel: "All active accounts"/)
  assert.match(panelSchema, /primary key \(scope, captured_day\)/)
})
