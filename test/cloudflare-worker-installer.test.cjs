test("Worker readiness rejects durable runtime errors without confusing them with deployment presence", () => {
  assert.equal(runtimeHealthError({ ok: true, state: { status: "idle" } }), null)
  assert.equal(runtimeHealthError({ ok: true, state: null }), null)
  assert.equal(runtimeHealthError({ ok: true, state: { status: "error", last_error: "Panel reconciliation failed (401)" } }), "Panel reconciliation failed (401)")
  assert.equal(runtimeHealthError({ ok: true, state: { status: "error", last_error: "Panel delivery reconciliation reported errors" } }), null)
  assert.equal(runtimeHealthError({ ok: true, state: { status: "failed", lastError: "database unavailable" } }), "database unavailable")
  assert.equal(runtimeHealthError({ ok: false, error: "not configured" }), "not configured")
  assert.match(runtimeHealthError("not-json"), /invalid status response/)
  assert.match(installer, /Runtime verification failed: \$\{healthError\}/)
  assert.match(installer, /Authenticated verification failed \(\$\{status\.status\}\)\$\{detail\}/)
  assert.match(installer, /current\.deployed = scriptPresent; current\.verified = false/)
})

test("installer deploys in dependency order and saves configuration before enabling", () => {
  assert.match(installer, /const ORDER: HostedWorker\[\] = \["backend", "scanner", "migration"\]/)
  const upload = installer.indexOf("for (const worker of ORDER)", installer.indexOf("queues_ready"))
  const save = installer.indexOf("configuration_saved")
  const verify = installer.indexOf("await verify", save)
  const schedules = installer.indexOf('state.step = "schedules_ready"', verify)
  const synchronize = installer.indexOf("await syncAllGitHubWorkerSecretsWithinInstallerLock({", schedules)
  const enable = installer.indexOf("saveRuntimeConfiguration(state, true)", verify)
  assert.ok(upload > 0 && upload < save && save < verify && verify < schedules && schedules < synchronize && synchronize < enable)
  const scheduling = installer.indexOf('state.step = "schedules_configuring"', verify)
  const scheduleLoop = installer.indexOf("await ensureSchedule(tokens[worker]", scheduling)
  assert.ok(scheduling > verify && scheduleLoop > scheduling)
  assert.doesNotMatch(installer.slice(scheduling, schedules), /await setSchedule\(tokens\[worker\]/)
})

